import Foundation

// MARK: - 剪贴板英文监测（“兼任翻译软件”）
//
// 设计要点：
// - 只轮询 changeCount（一个整数，系统已缓存，几微秒）；没变化时什么都不读，CPU 可忽略。
// - 变化后才读取类型和文本，交给纯函数 ClipboardTextFilter 判定是否弹出翻译。
// - 完全不在按键路径上：由 App 侧 0.5s 的 Timer（带 tolerance，允许系统合并唤醒）驱动。

/// 剪贴板判定结果
public enum ClipboardDecision: Equatable, Sendable {
    case translate(String)
    case ignore(ClipboardIgnoreReason)
}

public enum ClipboardIgnoreReason: Equatable, Sendable {
    case unchanged        // changeCount 没变
    case ownChange        // TranslateIME 自己写的（复制译文、上屏、恢复剪贴板）
    case disabled         // 菜单里关闭了监测
    case paused           // “暂停 1 小时”
    case busy             // 用户正在用翻译面板/组词，不打扰
    case sensitiveType    // 密码管理器等：Concealed / Transient / AutoGenerated
    case noText
    case tooShort         // 少于 2 个字母
    case tooLong          // 超过 2000 个字符
    case duplicate        // 与上一次弹出的文本相同
    case urlOnly
    case filePath
    case numeric          // 纯数字/符号
    case codeLike
    case shellCommand     // 终端命令 / shell 输出（ShellCommandDetector）
    case notEnglish
}

public enum ClipboardTextFilter {
    /// TranslateIME 写剪贴板时附带的私有类型
    public static let ownType = "com.example.inputmethod.TranslateIME.own"
    /// nspasteboard.org 约定的“不要记录/不要显示”类型 + 常见密码管理器私有类型
    public static let sensitiveTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping",
        "Pasteboard generator type",
    ]
    public static let minLetters = 2
    public static let maxCharacters = 2000

    public static func evaluate(text: String?, types: [String], lastText: String?) -> ClipboardDecision {
        if types.contains(ownType) { return .ignore(.ownChange) }
        if types.contains(where: { sensitiveTypes.contains($0) }) { return .ignore(.sensitiveType) }
        guard let raw = text else { return .ignore(.noText) }
        let t = raw.trimmingCharacters(in: .whitespacesAndNewlines)
        if t.isEmpty { return .ignore(.noText) }
        if t.count > maxCharacters { return .ignore(.tooLong) }
        let letters = t.unicodeScalars.filter { LanguageDetector.isLatinLetter($0) || LanguageDetector.isHan($0) }.count
        if letters < minLetters {
            let hasDigit = t.unicodeScalars.contains { CharacterSet.decimalDigits.contains($0) }
            return .ignore(hasDigit || letters == 0 ? .numeric : .tooShort)
        }
        if t == lastText { return .ignore(.duplicate) }
        if isFilePath(t) { return .ignore(.filePath) }
        if isURLOnly(t) { return .ignore(.urlOnly) }
        if isMostlyNumeric(t) { return .ignore(.numeric) }
        if ShellCommandDetector.isCommand(t) { return .ignore(.shellCommand) }
        if isCodeLike(t) { return .ignore(.codeLike) }
        guard LanguageDetector.detect(t) == .english else { return .ignore(.notEnglish) }
        return .translate(t)
    }

    // MARK: 规则

    static func tokens(_ t: String) -> [Substring] {
        t.split(whereSeparator: { $0 == " " || $0 == "\n" || $0 == "\t" || $0 == "\r" })
    }

    static func isURLOnly(_ t: String) -> Bool {
        let toks = tokens(t)
        guard !toks.isEmpty else { return false }
        return toks.allSatisfy { isURLToken(String($0)) }
    }

    static func isURLToken(_ s: String) -> Bool {
        let l = s.lowercased().trimmingCharacters(in: CharacterSet(charactersIn: "<>()[]\"'.,;"))
        if l.isEmpty { return false }
        if l.range(of: #"^[a-z][a-z0-9+.\-]*://\S+$"#, options: .regularExpression) != nil { return true }
        if l.hasPrefix("www.") || l.hasPrefix("mailto:") { return true }
        // 邮箱
        if l.range(of: #"^[^@\s]+@[^@\s]+\.[a-z]{2,}$"#, options: .regularExpression) != nil { return true }
        // 裸域名 / 域名+路径：example.com、github.com/foo
        if l.range(of: #"^([a-z0-9\-]+\.)+(com|net|org|io|dev|app|cn|co|ai|me|edu|gov|uk|jp|de|xyz|info)(/\S*)?$"#,
                   options: .regularExpression) != nil { return true }
        return false
    }

    static func isFilePath(_ t: String) -> Bool {
        guard !t.contains("\n") else {
            // 多行：每行都是路径
            let lines = t.split(separator: "\n").map { $0.trimmingCharacters(in: .whitespaces) }.filter { !$0.isEmpty }
            return !lines.isEmpty && lines.allSatisfy { isFilePath($0) }
        }
        if t.hasPrefix("file://") { return true }
        if t.range(of: #"^[A-Za-z]:\\"#, options: .regularExpression) != nil { return true }
        let starts = t.hasPrefix("/") || t.hasPrefix("~/") || t.hasPrefix("./") || t.hasPrefix("../")
        if starts {
            let slashes = t.filter { $0 == "/" }.count
            let spaces = t.filter { $0 == " " }.count
            // “/Users/a/b c.txt” 算路径；“/ this is a sentence” 不算
            return slashes >= 2 || spaces == 0
        }
        return false
    }

    static func isMostlyNumeric(_ t: String) -> Bool {
        var digits = 0, letters = 0
        for s in t.unicodeScalars {
            if CharacterSet.decimalDigits.contains(s) { digits += 1 }
            else if LanguageDetector.isLatinLetter(s) { letters += 1 }
        }
        // 订单号 / 金额 / 电话：数字远多于字母（如 “USD 1,234.56”、“#A12345678”）
        return digits >= 4 && digits > letters * 2
    }

    /// 只放英文句子里几乎不会出现的“代码味”片段（不放 return/let/class 这类普通英文单词）
    static let codeMarkers: [String] = [
        "func ", "#include", "=>", "->", "==", "!=", "&&", "||", "console.", "println", "printf(",
        "</", "/>", "{\n", "};", "();", "#!/", "sudo ", "npm ", "git ", "pip install", "brew install", "#import",
    ]

    static func isCodeLike(_ t: String) -> Bool {
        let toks = tokens(t)
        // 单个标识符：camelCase / snake_case / a.b.c / 带括号调用
        if toks.count == 1 {
            let s = String(toks[0])
            if s.contains("_") || s.contains("(") || s.contains("{") || s.contains("=") { return true }
            if s.range(of: #"^[a-z]+[A-Z][A-Za-z0-9]*$"#, options: .regularExpression) != nil { return true }   // camelCase
            if s.range(of: #"^[A-Za-z]+(\.[A-Za-z_]+){1,}\(?\)?$"#, options: .regularExpression) != nil,
               !s.hasSuffix(".") { return true }   // foo.bar.baz
        }
        let symbols = t.unicodeScalars.filter { "{}[]();=<>$\\|`".unicodeScalars.contains($0) }.count
        let total = max(1, t.unicodeScalars.count)
        if Double(symbols) / Double(total) > 0.08 && symbols >= 3 { return true }
        var markers = 0
        for m in codeMarkers where t.contains(m) { markers += 1; if markers >= 2 { return true } }
        // 多行且大多数行以 ; { } 结尾，或缩进代码块
        let lines = t.split(separator: "\n").map(String.init).filter { !$0.trimmingCharacters(in: .whitespaces).isEmpty }
        if lines.count >= 2 {
            let codeish = lines.filter { l in
                let r = l.trimmingCharacters(in: .whitespaces)
                return r.hasSuffix(";") || r.hasSuffix("{") || r.hasSuffix("}") || r.hasSuffix(")") || l.hasPrefix("    ") || l.hasPrefix("\t")
            }.count
            if Double(codeish) / Double(lines.count) >= 0.5 { return true }
        }
        return false
    }
}

/// 轮询那一刻翻译面板的状态（决定新复制的英文能不能弹出 / 覆盖）
public enum ClipboardPanelState: Equatable, Sendable {
    /// 面板没显示
    case idle
    /// 不打扰：TranslateIME 自己的窗口在前台、正在原应用里组词、或复制来自面板自身
    case busy
    /// 英文阅读面板：新的英文直接替换
    case reading(current: String?)
    /// 中→英回复（或 ⌃⌥T 中文输入）：新的外部英文覆盖回复模式，切回英文阅读
    case replying(current: String?)
}

/// 触发类型：App 侧据此决定是否暂存回复草稿、恢复输入源、取消旧回复
public enum ClipboardTriggerKind: Equatable, Sendable {
    case fresh            // 面板原本没显示
    case replaceReading   // 阅读面板换成新的英文
    case overrideReply    // 正在回复时复制了别的英文 → 切回阅读
}

/// 读剪贴板的抽象（测试里用 mock）
@MainActor
public protocol PasteboardReading: AnyObject {
    var changeCount: Int { get }
    func readTypes() -> [String]
    func readString() -> String?
}

/// 剪贴板监测器：App 侧每 ~0.5s 调用一次 poll()。
@MainActor
public final class ClipboardWatcher {
    private let pasteboard: PasteboardReading
    private let isEnabled: () -> Bool
    private let isBusy: () -> Bool
    private let panelState: (() -> ClipboardPanelState)?
    private let now: () -> Date
    public var pausedUntil: Date?
    public var onEnglishText: ((String) -> Void)?
    /// 设置后优先于 onEnglishText：带上触发类型
    public var onTrigger: ((String, ClipboardTriggerKind) -> Void)?
    public private(set) var lastTriggerKind: ClipboardTriggerKind?
    /// 最近一次 changeCount 变化时的判定（诊断用）
    public private(set) var lastDecision: ClipboardDecision?
    public private(set) var lastChangeCount: Int
    public private(set) var lastText: String?
    private var ownChangeCounts: [Int] = []

    public init(pasteboard: PasteboardReading,
                isEnabled: @escaping () -> Bool = { true },
                isBusy: @escaping () -> Bool = { false },
                panelState: (() -> ClipboardPanelState)? = nil,
                now: @escaping () -> Date = Date.init) {
        self.pasteboard = pasteboard
        self.isEnabled = isEnabled
        self.isBusy = isBusy
        self.panelState = panelState
        self.now = now
        // 启动时已有的剪贴板内容不弹出
        lastChangeCount = pasteboard.changeCount
    }

    public var isPaused: Bool { (pausedUntil.map { now() < $0 }) ?? false }

    /// TranslateIME 自己写完剪贴板后调用（传入写完后的 changeCount）
    public func markOwnChange(_ changeCount: Int) {
        ownChangeCounts.append(changeCount)
        if ownChangeCounts.count > 16 { ownChangeCounts.removeFirst(ownChangeCounts.count - 16) }
    }

    /// 重新同步，不弹出当前内容（例如刚重新开启监测时）
    public func resync() { lastChangeCount = pasteboard.changeCount }

    @discardableResult
    public func poll() -> ClipboardDecision {
        let d = evaluatePoll()
        if d != .ignore(.unchanged) { lastDecision = d }
        return d
    }

    private func evaluatePoll() -> ClipboardDecision {
        let cc = pasteboard.changeCount
        guard cc != lastChangeCount else { return .ignore(.unchanged) }
        lastChangeCount = cc
        if let i = ownChangeCounts.firstIndex(of: cc) {
            ownChangeCounts.remove(at: i)
            return .ignore(.ownChange)
        }
        guard isEnabled() else { return .ignore(.disabled) }
        if isPaused { return .ignore(.paused) }
        let state = panelState?() ?? (isBusy() ? .busy : .idle)
        if state == .busy { return .ignore(.busy) }
        let decision = ClipboardTextFilter.evaluate(text: pasteboard.readString(),
                                                    types: pasteboard.readTypes(),
                                                    lastText: lastText)
        guard case .translate(let text) = decision else { return decision }
        let kind: ClipboardTriggerKind
        let current: String?
        switch state {
        case .reading(let c): kind = .replaceReading; current = c
        case .replying(let c): kind = .overrideReply; current = c
        default: kind = .fresh; current = nil
        }
        // 与面板上正在显示/回复的英文相同：不打断
        if let c = current?.trimmingCharacters(in: .whitespacesAndNewlines), c == text { return .ignore(.duplicate) }
        lastText = text
        lastTriggerKind = kind
        if let onTrigger { onTrigger(text, kind) } else { onEnglishText?(text) }
        return decision
    }
}

// MARK: - 剪贴板触发的“英文阅读”面板：按键含义

public enum ReadingPanelKey: Equatable, Sendable {
    case returnKey, escape, commandShortcut, other
}

public enum ReadingPanelCommand: Equatable, Sendable {
    /// 切到中→英回复模式：清空输入、切简体拼音、聚焦输入框
    case startReply
    case close
    /// ⌘C 等快捷键：交给系统默认处理
    case passThrough
    /// 用户其实是想继续在原应用打字：关闭面板，把这个按键还给原应用
    case dismissAndForward
}

public enum ReadingPanelPolicy {
    public static func command(for key: ReadingPanelKey) -> ReadingPanelCommand {
        switch key {
        case .returnKey: return .startReply
        case .escape: return .close
        case .commandShortcut: return .passThrough
        case .other: return .dismissAndForward
        }
    }

    public static let hint = "↩ 用中文回复 · ⎋ 关闭 · 🔊 读英文"
    public static let replyHint = "输入中文 · ↩ 英文自动填入原输入框 · ⇧⌥↩ 复制并继续 · ⎋ 关闭"
    public static let replyHintCopyOnly = "输入中文 · ↩ 复制英文并关闭（回到原应用 ⌘V）· ⎋ 关闭"
    public static func replyHint(autoInsert: Bool) -> String { autoInsert ? replyHint : replyHintCopyOnly }
}
