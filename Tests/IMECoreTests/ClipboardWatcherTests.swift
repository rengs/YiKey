// MARK: - 剪贴板文本过滤（不误触发）

final class ClipboardFilterTests: XCTestCase {
    private func eval(_ text: String?, types: [String] = ["public.utf8-plain-text"], last: String? = nil) -> ClipboardDecision {
        ClipboardTextFilter.evaluate(text: text, types: types, lastText: last)
    }

    func testEnglishSentenceTriggers() {
        XCTAssertEqual(eval("  Could you send me the report by Friday?\n"), .translate("Could you send me the report by Friday?"))
        XCTAssertEqual(eval("serendipity"), .translate("serendipity"))
        XCTAssertEqual(eval("Let's meet at 3pm tomorrow."), .translate("Let's meet at 3pm tomorrow."))
        XCTAssertEqual(eval("OK"), .translate("OK"))
        // 普通英文里的 return / let / this. 不能被当成代码
        XCTAssertEqual(eval("Please return the form and let me know. I like this."),
                       .translate("Please return the form and let me know. I like this."))
    }

    func testChineseAndJapaneseIgnored() {
        XCTAssertEqual(eval("今天下午开会"), .ignore(.notEnglish))
        XCTAssertEqual(eval("我明天 send 给你"), .ignore(.notEnglish))   // 汉字多于英文单词 → 中文
        XCTAssertEqual(eval("ありがとう"), .ignore(.numeric))           // 无拉丁字母/汉字
    }

    func testSensitiveTypesIgnored() {
        for t in ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"] {
            XCTAssertEqual(eval("hunter2 password", types: ["public.utf8-plain-text", t]), .ignore(.sensitiveType), t)
        }
    }

    func testOwnPrivateTypeIgnored() {
        XCTAssertEqual(eval("Hello there", types: ["public.utf8-plain-text", ClipboardTextFilter.ownType]), .ignore(.ownChange))
    }

    func testURLsAndEmailsIgnored() {
        XCTAssertEqual(eval("https://www.apple.com/macos/"), .ignore(.urlOnly))
        XCTAssertEqual(eval("www.example.com"), .ignore(.urlOnly))
        XCTAssertEqual(eval("github.com/apple/swift"), .ignore(.urlOnly))
        XCTAssertEqual(eval("someone@example.com"), .ignore(.urlOnly))
        XCTAssertEqual(eval("https://a.com https://b.org/x"), .ignore(.urlOnly))
        // 句子里带链接仍然翻译
        XCTAssertEqual(eval("Please read https://example.com first"), .translate("Please read https://example.com first"))
    }

    func testFilePathsIgnored() {
        XCTAssertEqual(eval("/Users/someone/Documents/report.pdf"), .ignore(.filePath))
        XCTAssertEqual(eval("~/Library/Input Methods/TranslateIME.app"), .ignore(.filePath))
        XCTAssertEqual(eval("file:///tmp/a.txt"), .ignore(.filePath))
        XCTAssertEqual(eval("C:\\Windows\\System32"), .ignore(.filePath))
    }

    func testNumbersIgnored() {
        XCTAssertEqual(eval("1234567890"), .ignore(.numeric))
        XCTAssertEqual(eval("+1 (415) 555-0100"), .ignore(.numeric))
        XCTAssertEqual(eval("$1,299.00"), .ignore(.numeric))
        XCTAssertEqual(eval("#A12345678"), .ignore(.numeric))
        XCTAssertEqual(eval("Tel 400-820-8820 / 010-6552-9988"), .ignore(.numeric))
    }

    func testCodeIgnored() {
        XCTAssertEqual(eval("let x = foo(bar);"), .ignore(.codeLike))
        XCTAssertEqual(eval("func hello() {\n    print(\"hi\")\n}"), .ignore(.codeLike))
        XCTAssertTrue([.ignore(.codeLike), .ignore(.shellCommand)].contains(eval("if (a == b && c != d) { return; }")))   // 两条规则都会拦
        XCTAssertEqual(eval("myVariableName"), .ignore(.codeLike))
        XCTAssertEqual(eval("snake_case_name"), .ignore(.codeLike))
        XCTAssertEqual(eval("git checkout -b feature && npm install"), .ignore(.shellCommand))
    }

    func testTooShortAndTooLong() {
        XCTAssertEqual(eval("a"), .ignore(.tooShort))
        XCTAssertEqual(eval("   "), .ignore(.noText))
        XCTAssertEqual(eval(nil), .ignore(.noText))
        let long = String(repeating: "word ", count: 401)   // 2005 字符
        XCTAssertEqual(eval(long), .ignore(.tooLong))
        let ok = String(repeating: "word ", count: 399)
        if case .translate = eval(ok) {} else { XCTFail("2000 字以内应翻译") }
    }

    func testDuplicateOfLastTextIgnored() {
        XCTAssertEqual(eval("Thanks a lot!", last: "Thanks a lot!"), .ignore(.duplicate))
        XCTAssertEqual(eval(" Thanks a lot! \n", last: "Thanks a lot!"), .ignore(.duplicate))
        XCTAssertEqual(eval("Thanks again!", last: "Thanks a lot!"), .translate("Thanks again!"))
    }

    func testFilterIsFast() {
        let samples = ["Could you send me the report by Friday?", "https://example.com", "let x = foo(bar);",
                       "/Users/a/b.txt", "今天下午开会", String(repeating: "lorem ipsum ", count: 160)]
        let t0 = LatencyMonitor.now()
        for _ in 0..<200 { for s in samples { _ = eval(s) } }
        let per = LatencyMonitor.ms(since: t0) / Double(200 * samples.count)
        print("clipboard filter: \(String(format: "%.4f", per)) ms / evaluation")
        XCTAssertLessThan(per, 1.0)
    }
}

// MARK: - 监测器：轮询、自写忽略、开关、暂停

@MainActor
final class MockPasteboard: PasteboardReading {
    var changeCount = 100
    var types: [String] = []
    var string: String?
    private(set) var reads = 0
    func readTypes() -> [String] { reads += 1; return types }
    func readString() -> String? { reads += 1; return string }
    /// 模拟别的应用复制
    func copy(_ s: String, types: [String] = ["public.utf8-plain-text"]) { changeCount += 1; string = s; self.types = types }
}

@MainActor
final class ClipboardWatcherTests: XCTestCase {
    func testExistingClipboardAtStartupDoesNotTrigger() {
        let pb = MockPasteboard(); pb.string = "Hello world"
        let w = ClipboardWatcher(pasteboard: pb)
        var shown: [String] = []; w.onEnglishText = { shown.append($0) }
        XCTAssertEqual(w.poll(), .ignore(.unchanged))
        XCTAssertEqual(shown, [])
    }

    func testNewEnglishCopyTriggersOnce() {
        let pb = MockPasteboard()
        let w = ClipboardWatcher(pasteboard: pb)
        var shown: [String] = []; w.onEnglishText = { shown.append($0) }
        pb.copy("See you tomorrow")
        XCTAssertEqual(w.poll(), .translate("See you tomorrow"))
        XCTAssertEqual(w.poll(), .ignore(.unchanged), "同一 changeCount 只处理一次")
        pb.copy("See you tomorrow")                 // 再次复制同样内容
        XCTAssertEqual(w.poll(), .ignore(.duplicate))
        XCTAssertEqual(shown, ["See you tomorrow"])
    }

    func testUnchangedPollDoesNotReadPasteboard() {
        let pb = MockPasteboard()
        let w = ClipboardWatcher(pasteboard: pb)
        for _ in 0..<1000 { w.poll() }
        XCTAssertEqual(pb.reads, 0, "没变化时只读 changeCount，不读内容")
    }

    func testOwnWriteIgnoredByChangeCount() {
        let pb = MockPasteboard()
        let w = ClipboardWatcher(pasteboard: pb)
        var shown: [String] = []; w.onEnglishText = { shown.append($0) }
        // TranslateIME 复制自己的英文译文
        pb.copy("I will be there at five.")
        w.markOwnChange(pb.changeCount)
        XCTAssertEqual(w.poll(), .ignore(.ownChange))
        XCTAssertEqual(shown, [])
        // 之后用户复制别的英文照常弹出
        pb.copy("Great, thanks!")
        XCTAssertEqual(w.poll(), .translate("Great, thanks!"))
    }

    func testOwnWriteIgnoredByPrivateType() {
        let pb = MockPasteboard()
        let w = ClipboardWatcher(pasteboard: pb)
        pb.copy("I will be there at five.", types: ["public.utf8-plain-text", ClipboardTextFilter.ownType])
        XCTAssertEqual(w.poll(), .ignore(.ownChange))
    }

    func testToggleOffDoesNothingAndReenableDoesNotReplay() {
        let pb = MockPasteboard()
        var enabled = false
        let w = ClipboardWatcher(pasteboard: pb, isEnabled: { enabled })
        var shown: [String] = []; w.onEnglishText = { shown.append($0) }
        pb.copy("Hello there")
        XCTAssertEqual(w.poll(), .ignore(.disabled))
        XCTAssertEqual(pb.reads, 0, "关闭时不读剪贴板内容")
        enabled = true
        w.resync()
        XCTAssertEqual(w.poll(), .ignore(.unchanged), "重新开启不回放关闭期间的复制")
        pb.copy("Hello again")
        XCTAssertEqual(w.poll(), .translate("Hello again"))
        XCTAssertEqual(shown, ["Hello again"])
    }

    func testPauseOneHour() {
        let pb = MockPasteboard()
        var now = Date(timeIntervalSince1970: 1_000_000)
        let w = ClipboardWatcher(pasteboard: pb, now: { now })
        w.pausedUntil = now.addingTimeInterval(3600)
        XCTAssertTrue(w.isPaused)
        pb.copy("Paused text")
        XCTAssertEqual(w.poll(), .ignore(.paused))
        now = now.addingTimeInterval(3601)
        XCTAssertFalse(w.isPaused)
        pb.copy("Back again")
        XCTAssertEqual(w.poll(), .translate("Back again"))
    }

    func testBusyPanelNotInterrupted() {
        let pb = MockPasteboard()
        var busy = true
        let w = ClipboardWatcher(pasteboard: pb, isBusy: { busy })
        pb.copy("Hello there")
        XCTAssertEqual(w.poll(), .ignore(.busy))
        busy = false
        pb.copy("Hello world")
        XCTAssertEqual(w.poll(), .translate("Hello world"))
    }

    func testSensitiveCopyIgnored() {
        let pb = MockPasteboard()
        let w = ClipboardWatcher(pasteboard: pb)
        pb.copy("CorrectHorseBatteryStaple", types: ["public.utf8-plain-text", "org.nspasteboard.ConcealedType"])
        XCTAssertEqual(w.poll(), .ignore(.sensitiveType))
    }

    func testPollingCostIsNegligible() {
        let pb = MockPasteboard()
        let w = ClipboardWatcher(pasteboard: pb)
        let t0 = LatencyMonitor.now()
        for _ in 0..<100_000 { w.poll() }
        let perUs = LatencyMonitor.ms(since: t0) * 1000 / 100_000
        print("clipboard idle poll: \(String(format: "%.3f", perUs)) µs / tick")
        XCTAssertLessThan(perUs, 50)
        let t1 = LatencyMonitor.now()
        pb.copy("Could you review my pull request when you have a moment?")
        w.poll()
        let changedMs = LatencyMonitor.ms(since: t1)
        print("clipboard changed poll: \(String(format: "%.3f", changedMs)) ms")
        XCTAssertLessThan(changedMs, 3)
    }
}

// MARK: - 阅读模式 → ↩ 回复模式 → ↩ 复制英文（不再触发自己）

@MainActor
final class ReadingReplyFlowTests: XCTestCase {
    func testReturnStartsReplyEscapeCloses() {
        XCTAssertEqual(ReadingPanelPolicy.command(for: .returnKey), .startReply)
        XCTAssertEqual(ReadingPanelPolicy.command(for: .escape), .close)
        XCTAssertEqual(ReadingPanelPolicy.command(for: .commandShortcut), .passThrough)
        XCTAssertEqual(ReadingPanelPolicy.command(for: .other), .dismissAndForward)
        XCTAssertTrue(ReadingPanelPolicy.hint.contains("↩"))
        XCTAssertTrue(ReadingPanelPolicy.replyHint.contains("↩"))
    }

    /// 完整流程：别的应用复制英文 → 自动英译中；↩ 回复 → 输入中文 → ↩ 复制英文；自己复制的英文不再弹出
    func testFullReadReplyCopyFlow() async {
        let p = MockProvider(id: "p") { t, from, _ in from == .chinese ? "EN(\(t))" : "ZH(\(t))" }
        let speaker = MockSpeaker()
        let c = TranslationCoordinator(service: TranslationService(providers: [p]), speaker: speaker,
                                       debounce: 0, monitor: LatencyMonitor())
        let pb = MockPasteboard()
        let w = ClipboardWatcher(pasteboard: pb)
        // 复制器写剪贴板 = 模拟 OwnPasteboard：带私有类型并登记 changeCount
        final class OwnClipboard: ClipboardWriting {
            let pb: MockPasteboard; let w: ClipboardWatcher
            init(_ pb: MockPasteboard, _ w: ClipboardWatcher) { self.pb = pb; self.w = w }
            func write(_ text: String) {
                MainActor.assumeIsolated {
                    pb.copy(text, types: ["public.utf8-plain-text", ClipboardTextFilter.ownType])
                    w.markOwnChange(pb.changeCount)
                }
            }
        }
        let copier = TranslationCopier(coordinator: c, clipboard: OwnClipboard(pb, w))
        var reading: String?
        w.onEnglishText = { text in reading = text; c.reset(); c.update(text: text) }

        pb.copy("Are you free for a call this afternoon?")
        w.poll()
        XCTAssertEqual(reading, "Are you free for a call this afternoon?")
        await c.settle()
        XCTAssertEqual(c.result?.translated, "ZH(Are you free for a call this afternoon?)")
        XCTAssertTrue(c.canPronounceSource, "英文原文旁有 🔊")
        XCTAssertEqual(speaker.spoken, [], "不自动发音")

        // ↩ → 回复模式：清空、输入中文
        XCTAssertEqual(ReadingPanelPolicy.command(for: .returnKey), .startReply)
        c.reset()
        c.update(text: "可以，三点钟")
        await c.settle()
        // ↩ → 复制英文
        let r = await copier.copyTranslation(of: "可以，三点钟")
        XCTAssertEqual(r, .copied("EN(可以，三点钟)"))
        XCTAssertEqual(pb.string, "EN(可以，三点钟)")
        // 自己写的英文不触发阅读面板
        var shownAgain = false
        w.onEnglishText = { _ in shownAgain = true }
        XCTAssertEqual(w.poll(), .ignore(.ownChange))
        XCTAssertFalse(shownAgain)
    }
}
